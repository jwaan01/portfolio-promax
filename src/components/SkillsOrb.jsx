function SkillNode({ skill, index, total }) {
    const groupRef = useRef()
    const htmlRef = useRef()

    // Fibonacci sphere distribution
    const phi = Math.acos(1 - (2 * (index + 0.5)) / total)
    const goldenAngle = Math.PI * (3 - Math.sqrt(5))
    const theta = goldenAngle * index

    const RADIUS = 2.4
    const bx = RADIUS * Math.sin(phi) * Math.cos(theta)
    const by = RADIUS * Math.cos(phi)
    const bz = RADIUS * Math.sin(phi) * Math.sin(theta)

    useFrame((state) => {
        const t = state.clock.getElapsedTime()
        if (!groupRef.current) return

        // Orbit faster across latitude
        const orbitSpeed = 0.22 + (index % 5) * 0.03
        const orbitTheta = theta + t * orbitSpeed
        const x = RADIUS * Math.sin(phi) * Math.cos(orbitTheta)
        const y = RADIUS * Math.cos(phi) + Math.sin(t * 0.5 + index) * 0.06
        const z = RADIUS * Math.sin(phi) * Math.sin(orbitTheta)

        groupRef.current.position.set(x, y, z)

        // Face camera always
        groupRef.current.lookAt(state.camera.position)
    })

    return (
        <group ref={groupRef} position={[bx, by, bz]}>
            {/* Glowing dot behind icon */}
            <mesh>
                <sphereGeometry args={[0.1, 12, 12]} />
                <meshBasicMaterial color={skill.color} transparent opacity={0.85} />
            </mesh>
            <Html
                ref={htmlRef}
                center
                distanceFactor={6}
                style={{
                    pointerEvents: 'none',
                    userSelect: 'none',
                }}
            >
                <div className="skill-node-html">
                    <div className="skill-icon-wrap" style={{ borderColor: `${skill.color}44`, boxShadow: `0 0 12px ${skill.color}44` }}>
                        <div className="skill-svg" style={{ filter: `drop-shadow(0 0 4px ${skill.color}88)` }}>
                            {skill.icon}
                        </div>
                    </div>
                    <span className="skill-label" style={{ color: skill.color }}>{skill.name}</span>
                </div>
            </Html>
        </group>
    )
}

function ConnectionLines({ nodeData }) {
    const geoRef = useRef()

    const initialPositions = useMemo(() => {
        const total = nodeData.length
        return nodeData.map((_, index) => {
            const phi = Math.acos(1 - (2 * (index + 0.5)) / total)
            const goldenAngle = Math.PI * (3 - Math.sqrt(5))
            const theta = goldenAngle * index
            const RADIUS = 2.4
            return new THREE.Vector3(
                RADIUS * Math.sin(phi) * Math.cos(theta),
                RADIUS * Math.cos(phi),
                RADIUS * Math.sin(phi) * Math.sin(theta),
            )
        })
    }, [nodeData])

    const linePts = useMemo(() => {
        const pts = []
        for (let i = 0; i < initialPositions.length; i++) {
            for (let j = i + 1; j < initialPositions.length; j++) {
                if (initialPositions[i].distanceTo(initialPositions[j]) < 2.0) {
                    pts.push(initialPositions[i].clone(), initialPositions[j].clone())
                }
            }
        }
        return pts
    }, [initialPositions])

    const lineGeo = useMemo(() => new THREE.BufferGeometry().setFromPoints(linePts), [linePts])

    return (
        <lineSegments geometry={lineGeo}>
            <lineBasicMaterial color="#2563eb" transparent opacity={0.18} />
        </lineSegments>
    )
}

function SphereGroup({ nodeData }) {
    const groupRef = useRef()
    const mouse = useRef(new THREE.Vector2(0, 0))

    useEffect(() => {
        const onMouseMove = (e) => {
            mouse.current.x = (e.clientX / window.innerWidth) * 2 - 1
            mouse.current.y = -(e.clientY / window.innerHeight) * 2 + 1
        }
        window.addEventListener('mousemove', onMouseMove, { passive: true })
        return () => window.removeEventListener('mousemove', onMouseMove)
    }, [])

    useFrame(() => {
        if (!groupRef.current) return
        const tx = -mouse.current.y * 0.35
        const ty = mouse.current.x * 0.35
        groupRef.current.rotation.x += (tx - groupRef.current.rotation.x) * 0.09
        groupRef.current.rotation.y += (ty - groupRef.current.rotation.y) * 0.09
    })

    return (
        <group ref={groupRef}>
            {/* Core nucleus */}
            <mesh>
                <sphereGeometry args={[0.28, 32, 32]} />
                <meshStandardMaterial color="#001133" emissive="#4f8fff" emissiveIntensity={0.6} roughness={0.1} metalness={1} />
            </mesh>
            {/* Ghost sphere wireframe */}
            <mesh>
                <sphereGeometry args={[2.4, 20, 20]} />
                <meshBasicMaterial color="#1a56db" wireframe transparent opacity={0.06} />
            </mesh>
            {/* Equatorial ring */}
            <mesh rotation={[Math.PI / 2, 0, 0]}>
                <torusGeometry args={[2.5, 0.01, 6, 80]} />
                <meshBasicMaterial color="#4f8fff" transparent opacity={0.3} />
            </mesh>
            <ConnectionLines nodeData={nodeData} />
            {nodeData.map((skill, i) => (
                <SkillNode key={skill.name} skill={skill} index={i} total={nodeData.length} />
            ))}
        </group>
    )
}

